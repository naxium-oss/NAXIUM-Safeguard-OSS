import { timingSafeEqual as nodeTimingSafeEqual, createHash } from 'node:crypto';

/**
 * Constant-time string comparison. Hashes both sides so unequal lengths
 * do not short-circuit and length is not leaked via early return.
 */
export function timingSafeEqualString(a: string, b: string): boolean {
  const ha = createHash('sha256').update(a, 'utf8').digest();
  const hb = createHash('sha256').update(b, 'utf8').digest();
  return nodeTimingSafeEqual(ha, hb);
}
